def merge(path, adds):
    data = json.loads(path.read_text(encoding="utf-8"))
    before = len(data)
    for k, v in adds.items():
        if k not in data:
            data[k] = v          # append; existing order and formatting kept
    path.write_text(json.dumps(data, ensure_ascii=False, indent=1) + "\n",
                    encoding="utf-8")
    return before, len(data)

